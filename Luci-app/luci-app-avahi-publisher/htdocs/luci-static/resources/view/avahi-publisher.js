'use strict';
'require view';
'require fs';
'require uci';
'require form';

function parseStatus(result) {
	if (!result || result.code !== 0 || !result.stdout)
		return {};

	try {
		return JSON.parse(result.stdout);
	}
	catch (e) {
		return {};
	}
}

function statusBadge(ok, yesText, noText) {
	return E('span', {
		'class': 'label %s'.format(ok ? 'success' : 'warning')
	}, [ ok ? yesText : noText ]);
}

return view.extend({
	load: function() {
		return Promise.all([
			uci.load('avahi-publisher'),
			L.resolveDefault(fs.exec('/usr/libexec/avahi-publisher', [ 'status' ]), null)
		]);
	},

	render: function(data) {
		var status = parseStatus(data[1]);
		var m, s, o;

		m = new form.Map('avahi-publisher',
			_('Avahi Service Publisher'),
			_('Publish Bonjour/DNS-SD discovery records through the router for services hosted by other LAN devices. This application publishes discovery metadata only; clients connect directly to the target host.'));

		s = m.section(form.GridSection, '_runtime');
		s.render = function() {
			return E('div', { 'class': 'cbi-section' }, [
				E('h3', {}, [ _('Runtime status') ]),
				E('div', { 'class': 'table' }, [
					E('div', { 'class': 'tr' }, [
						E('div', { 'class': 'td left', 'style': 'width:25%' }, [
							E('strong', {}, [ _('Avahi') ]),
							' ',
							statusBadge(status.avahi_running === true,
								_('Running'), _('Not running'))
						]),
						E('div', { 'class': 'td left', 'style': 'width:25%' }, [
							E('strong', {}, [ _('Enabled entries') ]),
							': %s / %s'.format(status.enabled || 0,
								status.configured || 0)
						]),
						E('div', { 'class': 'td left', 'style': 'width:25%' }, [
							E('strong', {}, [ _('Generated service files') ]),
							': %s'.format(status.generated || 0)
						]),
						E('div', { 'class': 'td left', 'style': 'width:25%' }, [
							E('strong', {}, [ _('Published host addresses') ]),
							': %s'.format(status.addresses || 0)
						])
					])
				]),
				E('p', { 'class': 'cbi-section-descr' }, [
					_('Saving the configuration reloads the managed Avahi records. An offline target does not prevent saving and can use the same discovery record when it comes back online.')
				])
			]);
		};

		s = m.section(form.NamedSection, 'main', 'main', _('Global settings'));
		s.addremove = false;

		o = s.option(form.Flag, 'enabled', _('Enable managed publishing'),
			_('Disabling this option removes records generated by this application without stopping Avahi or changing records owned by other applications.'));
		o.default = '1';
		o.rmempty = false;

		s = m.section(form.GridSection, 'service', _('Managed services'),
			_('Each entry points a DNS-SD service instance to the LAN host that actually provides the service.'));
		s.anonymous = true;
		s.addremove = true;
		s.sortable = true;

		o = s.option(form.Flag, 'enabled', _('Enabled'));
		o.default = '1';
		o.rmempty = false;
		o.editable = true;

		o = s.option(form.Value, 'name', _('Display name'));
		o.placeholder = _('Office NAS');
		o.rmempty = false;
		o.validate = function(sectionId, value) {
			if (!value || /[\x00-\x1f\x7f]/.test(value))
				return _('The display name must not be empty or contain control characters.');
			return true;
		};

		o = s.option(form.Value, 'host', _('Target host'),
			_('Enter a fully-qualified host name, for example nas.local. If it is not already resolvable, also enter its static IPv4 address.'));
		o.placeholder = 'nas.local';
		o.rmempty = false;
		o.validate = function(sectionId, value) {
			var pattern = /^([A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?\.)+[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?\.?$/;
			if (!pattern.test(value || ''))
				return _('Enter a fully-qualified host name such as nas.local.');
			return true;
		};

		o = s.option(form.Value, 'address', _('Target IPv4 address'),
			_('Optional. Publishes an A record for the target host when that device does not publish its own mDNS address.'));
		o.datatype = 'ip4addr';
		o.placeholder = '192.0.2.10';
		o.rmempty = true;

		o = s.option(form.Value, 'type', _('Service type'));
		o.value('_smb._tcp', 'SMB (_smb._tcp)');
		o.value('_ssh._tcp', 'SSH (_ssh._tcp)');
		o.value('_http._tcp', 'HTTP (_http._tcp)');
		o.value('_https._tcp', 'HTTPS (_https._tcp)');
		o.value('_rdp._tcp', 'RDP (_rdp._tcp)');
		o.placeholder = '_smb._tcp';
		o.rmempty = false;
		o.validate = function(sectionId, value) {
			var pattern = /^_[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?\._(tcp|udp)$/;
			if (!pattern.test(value || ''))
				return _('Use a DNS-SD service type such as _smb._tcp.');
			return true;
		};

		o = s.option(form.Value, 'port', _('Port'));
		o.datatype = 'port';
		o.placeholder = '445';
		o.rmempty = false;

		o = s.option(form.ListValue, 'protocol', _('Address protocol'));
		o.value('any', _('IPv4 and IPv6'));
		o.value('ipv4', _('IPv4 only'));
		o.value('ipv6', _('IPv6 only'));
		o.default = 'any';
		o.rmempty = false;

		return m.render();
	}
});
